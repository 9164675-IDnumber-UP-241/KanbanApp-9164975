package ua.opu.kanbanapp.data.model

// ===== КРОК 1: Enum для всіх можливих статусів завдання =====
// Кожен статус відповідає одній колонці на Kanban дошці
// Порядок важливий: завдання рухаються зліва направо
enum class TaskStatus {
    TODO,           // Колонка 1: Невпроцесовано (нові завдання стартують тут)
    IN_PROGRESS,    // Колонка 2: В прогресі (робота над завданням)
    REVIEW,         // Колонка 3: На перевірці (чекаємо перевірки)
    DONE            // Колонка 4: Готово (завершені завдання, інша логіка)
}

/*
Чому Enum?
──────────
1. Безпека типів: компілятор не дозволить неправильний статус
2. Простота: всього 4 значення, не потрібна база даних
3. Використання в when(): Kotlin автоматично перевіряє всі варіанти
*/